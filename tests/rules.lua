local rules = dofile(ROOT .. '/src/ServerScriptService/MatchRules.lua')
assert(rules.canDamage('TDM', true, 1, 2, 'Red', 'Blue'))
assert(not rules.canDamage('TDM', true, 1, 2, 'Red', 'Red'))
assert(not rules.canDamage('TDM', true, 1, 2, nil, 'Blue'))
assert(rules.canDamage('FFA', true, 1, 2, nil, nil))
assert(not rules.canDamage('FFA', true, 1, 1, nil, nil))
assert(not rules.canDamage('FFA', false, 1, 2, nil, nil))
assert(not rules.canDamage('UNKNOWN', true, 1, 2, nil, nil))
assert(rules.winner('TDM', {Red=5, Blue=2}, {}) == 'Red')
assert(rules.winner('TDM', {Red=2, Blue=5}, {}) == 'Blue')
assert(rules.winner('TDM', {Red=2, Blue=2}, {}) == 'Draw')
assert(rules.winner('FFA', {}, {[1]=4, [2]=3}) == '1')
assert(rules.winner('FFA', {}, {[1]=4, [2]=4}) == 'Draw')
assert(rules.winner('FFA', {}, {[1]=0, [2]=0}) == 'Draw')
assert(rules.winner('FFA', {}, {}) == 'Draw')
assert(rules.winner('FFA', {}, {[1]=4, [2]=4, [3]=5}) == '3')
